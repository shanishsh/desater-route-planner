package com.touristsafety.app.core.push

import android.util.Log
import com.google.firebase.messaging.FirebaseMessagingService
import com.google.firebase.messaging.RemoteMessage
import com.touristsafety.app.core.notification.DisasterNotificationManager
import dagger.hilt.android.AndroidEntryPoint
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.launch
import javax.inject.Inject

/**
 * Handles incoming Firebase Cloud Messaging (FCM) events, token rotation,
 * and background emergency alert dispatches.
 */
@AndroidEntryPoint
class AppFirebaseMessagingService : FirebaseMessagingService() {

    companion object {
        private const val TAG = "AppFirebaseMessaging"
    }

    @Inject
    lateinit var deviceRegistrationHelper: DeviceRegistrationHelper

    @Inject
    lateinit var disasterNotificationManager: DisasterNotificationManager

    private val serviceScope = CoroutineScope(Dispatchers.IO + SupervisorJob())

    /**
     * Called whenever a new FCM registration token is generated by Firebase.
     * Automatically syncs the updated token to the backend device installation registry.
     */
    override fun onNewToken(token: String) {
        super.onNewToken(token)
        val maskedToken = if (token.length > 10) "${token.take(6)}...${token.takeLast(4)}" else "***"
        Log.i(TAG, "New FCM registration token received from Firebase: $maskedToken")

        serviceScope.launch {
            try {
                deviceRegistrationHelper.updateFcmToken(token)
            } catch (t: Throwable) {
                Log.w(TAG, "Failed to sync refreshed FCM token to backend: ${t.message}")
            }
        }
    }

    /**
     * Called when a message is received while the app is in the foreground or background.
     * Decodes hazard advisories or community trail reports and triggers emergency notifications.
     */
    override fun onMessageReceived(remoteMessage: RemoteMessage) {
        super.onMessageReceived(remoteMessage)
        Log.i(TAG, "FCM message received from: ${remoteMessage.from}")

        val data = remoteMessage.data
        if (data.isNotEmpty()) {
            val alertId = data["alert_id"] ?: ("fcm_alert_" + System.currentTimeMillis())
            val title = data["title"] ?: (remoteMessage.notification?.title ?: "Emergency Alert")
            val body = data["body"] ?: (remoteMessage.notification?.body ?: "Emergency conditions detected along active corridor.")
            val severity = data["severity"] ?: "WARNING"
            val category = data["category"] ?: "HAZARD"
            val authority = data["authority"] ?: "State Emergency Operations Centre"
            val isSimulated = data["is_simulated"]?.toBoolean() ?: false

            Log.i(TAG, "Processing FCM push alert [$severity]: $title")

            disasterNotificationManager.showDisasterNotification(
                alertId = alertId,
                title = title,
                instructions = body,
                category = category,
                issuingAuthority = authority,
                isCached = false,
                isSimulated = isSimulated,
                isTestAlarm = false
            )
        } else {
            remoteMessage.notification?.let { notif ->
                val title = notif.title ?: "Tourist Safety Alert"
                val body = notif.body ?: "New safety update received."
                disasterNotificationManager.showDisasterNotification(
                    alertId = "fcm_notif_" + System.currentTimeMillis(),
                    title = title,
                    instructions = body,
                    category = "ADVISORY",
                    issuingAuthority = "Uttarakhand Disaster Safety Management",
                    isCached = false,
                    isSimulated = false,
                    isTestAlarm = false
                )
            }
        }
    }
}

